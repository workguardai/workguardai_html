// Builds the static pages from src/page.html and src/i18n/<lang>.json.
//   en  -> index.html
//   xx  -> xx/index.html
// Run: node scripts/build.mjs
import { readFile, writeFile, mkdir } from 'node:fs/promises';

const config = JSON.parse(await readFile('site.config.json', 'utf8'));
const template = await readFile('src/page.html', 'utf8');
const LANGS = config.languages;
const LABELS = { en: 'EN', sq: 'SQ', da: 'DA', fi: 'FI', es: 'ES' };
const NAMES = { en: 'English', sq: 'Shqip', da: 'Dansk', fi: 'Suomi', es: 'Español' };

const dicts = {};
for (const lang of LANGS) dicts[lang] = JSON.parse(await readFile(`src/i18n/${lang}.json`, 'utf8'));

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const pathOf = (lang) => (lang === 'en' ? '' : `${lang}/`);
const urlOf = (lang) => `${config.baseUrl}/${pathOf(lang)}`;

const usedKeys = new Set([...template.matchAll(/\{\{([^@}][^}]*)\}\}/g)].map((m) => m[1]));
let problems = 0;
for (const key of usedKeys) {
  if (!(key in dicts.en)) { console.error(`en.json is missing "${key}"`); problems++; }
}

for (const lang of LANGS) {
  const t = dicts[lang];
  const missing = [...usedKeys].filter((k) => !(k in t));
  if (missing.length) console.warn(`${lang}: ${missing.length} missing, using English: ${missing.join(', ')}`);

  const base = lang === 'en' ? '' : '../';
  const langnav = LANGS.map((l) => {
    const href = base + pathOf(l) || './';
    const current = l === lang ? ' aria-current="true"' : '';
    return `        <a href="${href}" hreflang="${l}" lang="${l}" title="${NAMES[l]}"${current}>${LABELS[l]}</a>`;
  }).join('\n');
  const alternates = [
    ...LANGS.map((l) => `<link rel="alternate" hreflang="${l}" href="${urlOf(l)}">`),
    `<link rel="alternate" hreflang="x-default" href="${urlOf('en')}">`,
  ].join('\n');
  const formReady = Boolean(config.formspreeId);

  const vars = {
    lang,
    base,
    home: base || './',
    canonical: urlOf(lang),
    alternates,
    langnav,
    robots: config.noindex ? '<meta name="robots" content="noindex">' : '',
    formAction: formReady ? `https://formspree.io/f/${config.formspreeId}` : '#',
    formDisabled: formReady ? '' : ' disabled',
    formTodo: formReady ? '' : ' <span class="todo">[TODO: Formspree form ID in site.config.json]</span>',
  };

  let html = template
    .replace(/\{\{@(\w+)\}\}/g, (_, k) => {
      if (!(k in vars)) throw new Error(`Unknown build variable @${k}`);
      return vars[k];
    })
    .replace(/\{\{([^}]+)\}\}/g, (_, k) => esc(t[k] ?? dicts.en[k] ?? `[MISSING ${k}]`));

  const status = t._meta?.status ?? 'unknown';
  html = html.replace('<!doctype html>', `<!doctype html>\n<!-- Generated by scripts/build.mjs from src/page.html and src/i18n/${lang}.json (${status}). Do not edit by hand. -->`);

  const out = lang === 'en' ? 'index.html' : `${lang}/index.html`;
  if (lang !== 'en') await mkdir(lang, { recursive: true });
  await writeFile(out, html);
  console.log(`wrote ${out}${status === 'needs native review' ? '  (needs native review)' : ''}`);
}

if (problems) process.exit(1);
